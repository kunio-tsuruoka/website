const jsonHeaders = {
  'content-type': 'application/json; charset=utf-8',
  'cache-control': 'no-store',
  'x-robots-tag': 'noindex, nofollow',
};

async function parseResponse(response: Response) {
  const text = await response.text();
  try {
    return text ? JSON.parse(text) : {};
  } catch {
    return { raw: text };
  }
}

export const GET: APIRoute = async ({ locals }) => {
  const runtime = (locals as { runtime?: { env?: RuntimeEnv } }).runtime;
  const env = runtime?.env ?? {};
  const serviceDomain = env.MICROCMS_SERVICE_DOMAIN ?? '';
  const apiKey = env.MICROCMS_API_KEY ?? '';

  if (!serviceDomain || !apiKey) {
    return new Response(
      JSON.stringify({
        ok: false,
        error: 'microcms_env_missing',
        hasServiceDomain: Boolean(serviceDomain),
        hasApiKey: Boolean(apiKey),
      }),
      { status: 503, headers: jsonHeaders }
    );
  }

  const endpoint = `https://${serviceDomain}.microcms.io/api/v1/blogs`;
  const headers = {
    'X-MICROCMS-API-KEY': apiKey,
    'content-type': 'application/json',
  };
  const payload = {
    title: TITLE,
    description: DESCRIPTION,
    content: CONTENT,
  };

  try {
    const current = await fetch(`${endpoint}/${encodeURIComponent(CONTENT_ID)}`, {
      headers: { 'X-MICROCMS-API-KEY': apiKey },
    });

    const method = current.status === 404 ? 'PUT' : 'PATCH';
    if (!current.ok && current.status !== 404) {
      const data = await parseResponse(current);
      return new Response(
        JSON.stringify({ ok: false, stage: 'lookup', status: current.status, data }),
        { status: 502, headers: jsonHeaders }
      );
    }

    const publish = await fetch(`${endpoint}/${encodeURIComponent(CONTENT_ID)}`, {
      method,
      headers,
      body: JSON.stringify(payload),
    });
    const data = await parseResponse(publish);

    if (!publish.ok) {
      return new Response(
        JSON.stringify({ ok: false, stage: 'publish', method, status: publish.status, data }),
        { status: 502, headers: jsonHeaders }
      );
    }

    return new Response(
      JSON.stringify({
        ok: true,
        action: method === 'PUT' ? 'created' : 'updated',
        id: CONTENT_ID,
        title: TITLE,
        url: `https://beekle.jp/blog/${CONTENT_ID}`,
        microcms: data,
      }),
      { status: 200, headers: jsonHeaders }
    );
  } catch (error) {
    return new Response(
      JSON.stringify({
        ok: false,
        error: error instanceof Error ? error.message : 'unknown_error',
      }),
      { status: 500, headers: jsonHeaders }
    );
  }
};
