type Section = NonNullable<ServiceDetail['additionalSections']>[number];

type ModelCase = {
  /** 何の仕組みか（見出しの後半） */
  subject: string;
  /** 実績（事実）。実案件で作った範囲。数字は検証済みのものだけ */
  fact: string;
  /** モデルケース。対象・作る範囲・期間・費用 */
  model: string;
  /** 本番展開の目安 */
  production: string;
  /** 別料金になる条件 */
  extra: string;
  cards: { title: string; description: string }[];
};

const NOTE =
  '上記のモデルケースは、Beekleの過去の開発案件をもとに条件を組み替えたものです。金額はすべて税別で、本番展開の目安は検証費用に上乗せする追加額ではなく、その段階の総額です。実際の費用と期間は、対象業務、利用するデータ、既存システムとの連携、精度要件、権限・セキュリティ要件によって変わります。初回相談と、完成イメージを合わせる簡易デモは無料です。実データでの精度検証や個別の連携を含むPoCからは、範囲と費用をご提示したうえで進めます。';

function build(mc: ModelCase): Section {
  return {
    title: `費用・期間のモデルケース｜${mc.subject}`,
    subtitle: '実績と、条件を組み替えたモデルケース',
    paragraphs: [
      '金額は、対象業務と連携先、データの状態で動きます。',
      `実績（事実）: ${mc.fact}`,
      `モデルケース: ${mc.model}`,
      `本番展開の目安: ${mc.production}`,
      `別料金になるもの: ${mc.extra}`,
      NOTE,
    ],
    cards: mc.cards,
  };
}

